const ROLE_CODE: Record<string, Role> = { S: 'subject', V: 'verb', O: 'object', M: 'modifier', X: 'other' };
/** 'S:แมว|V:กิน|O:ปลา' → บล็อกคำ (S ผู้ทำ, V การกระทำ, O ผู้รับการกระทำ, M คำขยาย/เวลา/สถานที่, X อื่น ๆ) */
export function words(spec: string): StarterWord[] {
  return spec.split('|').map((s) => {
    const [code, text] = s.split(':');
    return { text, role: ROLE_CODE[code] ?? 'other' };
  });
}

